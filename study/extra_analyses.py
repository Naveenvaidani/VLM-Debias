"""Analyses of the round 3-4 control runs (reviewer requests), written to one Markdown file.

  1. H1 across the four LLM x task cells: paired t, df, d_z, Holm-adjusted p.
  2. Open gate (tanh alpha = 0.995 at init, learnable) vs learned (alpha = 0) and fixed gate, same seeds.
  3. Connector learning rate 5e-5 / 2e-4 (default) / 1e-3: does a faster-moving gate close the gap?
  4. 10x longer alignment (3,000 steps): does the gate open with more alignment?
  5. Group DRO instead of ERM: does a group-robust loss remove the gate effect?
  6. Injection ratio ||injected|| / ||text||: how much visual signal each gate lets through.
  7. SigLIP-large (stronger encoder) and CelebA (third task).

Values are test worst-group accuracy (WGA, %), checkpoint selected by validation WGA, mean over prompt templates.

    python study/extra_analyses.py --dl kaggle_out/dl --out results_study/extra_analyses.md
"""
import argparse
import glob
import json
import os

import numpy as np
from scipy import stats


def runs(root):
    """{(connector, seed): results dict} for one run_dir/task folder."""
    out = {}
    for f in glob.glob(os.path.join(root, "*", "s*", "results.json")):
        conn, seed = f.split(os.sep)[-3], int(f.split(os.sep)[-2][1:])
        out[(conn, seed)] = json.load(open(f))
    return out


def wga(r):
    return 100 * r["test"]["wga"]["mean_over_templates"]["worst_group_acc"]


def avg(r):
    return 100 * r["test"]["wga"]["mean_over_templates"]["avg_acc"]


def inj(r):
    return r["test"]["wga"]["mean_over_templates"].get("inject_ratio")


def final_gate(r):
    h = r.get("history") or []
    g = h[-1].get("gate_tanh") if h else None
    return abs(g) if isinstance(g, (int, float)) else None


def paired(a, b, conns=("bottleneck", "bottleneck_fixed")):
    seeds = sorted({s for c, s in a if c == conns[0]} & {s for c, s in b if c == conns[1]})
    return seeds, np.array([wga(a[(conns[0], s)]) for s in seeds]), np.array([wga(b[(conns[1], s)]) for s in seeds])


def fmt(x):
    return f"{np.mean(x):.1f} ± {np.std(x, ddof=1):.1f}" if len(x) > 1 else f"{x[0]:.1f}"


def cell(rs, conn, seeds):
    v = [wga(rs[(conn, s)]) for s in seeds if (conn, s) in rs]
    return (fmt(v), len(v)) if v else ("–", 0)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--dl", default="kaggle_out/dl")
    p.add_argument("--h1", default="kaggle_out/h1_merged/qwen35-4b")
    p.add_argument("--phi", default="kaggle_out/phi_all/phi-4-mini-instruct")
    p.add_argument("--siglip", default="kaggle_out/siglip_all/qwen35-4b_siglip-large")
    p.add_argument("--celeba", default="kaggle_out/celeba_all/celeba")
    p.add_argument("--out", default="results_study/extra_analyses.md")
    a = p.parse_args()
    dl = lambda job, tag, task: os.path.join(a.dl, job, "results", tag, task)
    TASKS = ("waterbirds", "watermark_p0.95")
    H1 = {t: runs(os.path.join(a.h1, t)) for t in TASKS}
    L = ["# Control analyses (round 3-4 runs)", "",
         "Generated by `study/extra_analyses.py`. Test worst-group accuracy (%), checkpoint chosen by validation WGA, "
         "mean ± SD over seeds. Learned = tanh gate initialised at 0; fixed = gate fixed at 1; "
         "open = learnable gate initialised at α = 3 (tanh = 0.995).", ""]

    # 1. H1 + Holm
    L += ["## 1. H1 in the four cells, with Holm correction", "",
          "| LLM | Task | Seeds | Gain | t (df) | p one-sided | d_z | Holm-adjusted p |",
          "| :--- | :--- | :---: | ---: | :---: | ---: | ---: | ---: |"]
    rows = []
    for llm, root in (("Qwen3.5-4B", a.h1), ("Phi-4-mini", a.phi)):
        for t in TASKS:
            rs = runs(os.path.join(root, t))
            seeds, lo, fx = paired(rs, rs)
            d = fx - lo
            tt = stats.ttest_rel(fx, lo, alternative="greater")
            rows.append([llm, t, len(seeds), d.mean(), tt.statistic, len(seeds) - 1, tt.pvalue, d.mean() / d.std(ddof=1)])
    order = np.argsort([r[6] for r in rows])
    adj, run_max = [0.0] * 4, 0.0
    for rank, i in enumerate(order):
        run_max = max(run_max, min(1.0, (4 - rank) * rows[i][6]))
        adj[i] = run_max
    for r, h in zip(rows, adj):
        L.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]:+.1f} | {r[4]:.2f} ({r[5]}) | {r[6]:.2g} | {r[7]:.2f} | **{h:.2g}** |")
    L += ["", f"All four cells survive Holm at one-sided α = 0.025: {all(h < 0.025 for h in adj)}.", ""]

    # 2. open gate
    L += ["## 2. Open gate: is it the initial value or the learnability?", "",
          "The open gate is learnable like the learned gate, but starts at tanh = 0.995 instead of 0. "
          "Same seeds (0-4), same alignment budget.", "",
          "| Task | Seeds | Learned (α=0) | Open (α=3, learnable) | Fixed (1) | Open − learned (p) | Fixed − open (p, two-sided) | final tanh, open |",
          "| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: |"]
    for t in TASKS:
        op = runs(dl("vlm-shortcut-r3-opengate", "qwen35-4b", t))
        s = sorted(x for c, x in op if c == "bottleneck_open" and ("bottleneck", x) in H1[t])
        lo = np.array([wga(H1[t][("bottleneck", x)]) for x in s])
        fx = np.array([wga(H1[t][("bottleneck_fixed", x)]) for x in s])
        o = np.array([wga(op[("bottleneck_open", x)]) for x in s])
        g = np.mean([final_gate(op[("bottleneck_open", x)]) for x in s])
        L.append(f"| {t} | {len(s)} | {fmt(lo)} | {fmt(o)} | {fmt(fx)} | {o.mean() - lo.mean():+.1f} "
                 f"({stats.ttest_rel(o, lo, alternative='greater').pvalue:.2g}) | {fx.mean() - o.mean():+.1f} "
                 f"({stats.ttest_rel(fx, o).pvalue:.2g}) | {g:.3f} |")
    L += ["", "Reading: a learnable gate that *starts* open stays open (tanh ≈ 0.994) and matches the fixed gate. "
          "The harm comes from initialising the gate at zero, not from making it learnable. Caveat: at α = 3 the "
          "gate gradient is scaled by 1 − tanh² ≈ 0.01, so the open gate moves little; it is learnable in form, "
          "nearly fixed in practice.", ""]

    # 3. learning rate
    L += ["## 3. Connector learning rate (Waterbirds, seeds 0-1)", "",
          "| Connector LR | Learned | Fixed | MLP | Fixed − learned | final abs(tanh α), learned |",
          "| :--- | :---: | :---: | :---: | ---: | ---: |"]
    for lab, tag in (("5e-5", "qwen35-4b_lr5e-5"), ("2e-4 (default)", None), ("1e-3", "qwen35-4b_lr1e-3")):
        rs = H1["waterbirds"] if tag is None else runs(dl("vlm-shortcut-r3-lr", tag, "waterbirds"))
        s = [0, 1]
        lo = [wga(rs[("bottleneck", x)]) for x in s]
        fx = [wga(rs[("bottleneck_fixed", x)]) for x in s]
        mlp = cell(rs, "mlp", s)[0]
        # the default-LR runs predate per-epoch gate logging; take the gate from the r4-inject rerun of the same setting
        gr = runs(dl("vlm-shortcut-r4-inject", "qwen35-4b_inject", "waterbirds")) if tag is None else rs
        g = np.mean([final_gate(gr[("bottleneck", x)]) for x in s])
        L.append(f"| {lab} | {fmt(lo)} | {fmt(fx)} | {mlp} | {np.mean(fx) - np.mean(lo):+.1f} | {g:.4f} |")
    L += ["", "Reading: the gap shrinks as the connector learning rate grows (+29.6, +16.7, +0.7), and the learned "
          "gate moves further from zero (0.002, 0.004, 0.018): a dose-response pattern. At 1e-3 part of the closing "
          "comes from the fixed gate getting worse (66.5 vs 73.5). Two seeds per setting: descriptive only.", ""]

    # 4. align3k
    L += ["## 4. 10× longer alignment (3,000 steps vs 300), seeds 0-2", "",
          "| Task | Alignment | Learned | Fixed | Fixed − learned | tanh α after alignment |",
          "| :--- | :--- | :---: | :---: | ---: | ---: |"]
    al3 = json.load(open(glob.glob(os.path.join(a.dl, "vlm-shortcut-r3-align3k", "results", "qwen35-4b_align3k", "align", "bottleneck", "align.json"))[0]))
    g3 = al3["gate_trace"][-1]["tanh"]
    peak3 = max(abs(x["tanh"]) for x in al3["gate_trace"])
    for t in TASKS:
        rs3 = runs(dl("vlm-shortcut-r3-align3k", "qwen35-4b_align3k", t))
        for lab, rs, g in (("300 steps (default)", H1[t], None), ("3,000 steps", rs3, g3)):
            s = [0, 1, 2]
            lo = [wga(rs[("bottleneck", x)]) for x in s]
            fx = [wga(rs[("bottleneck_fixed", x)]) for x in s]
            L.append(f"| {t} | {lab} | {fmt(lo)} | {fmt(fx)} | {np.mean(fx) - np.mean(lo):+.1f} | "
                     f"{'≈ 0.0006' if g is None else f'{g:.5f} (peak abs {peak3:.4f})'} |")
    L += ["", "Reading: ten times more alignment does not open the gate (peak |tanh α| 0.003, final −0.0002), and the "
          "learned-gate model collapses to the shortcut (WGA 11 and 4: it predicts the spurious class for the "
          "minority groups), while the fixed gate changes little (−2.7 and −10.1). Longer alignment widens the gap "
          "rather than closing it, which answers the 'Flamingo trains longer' objection for our regime.", ""]

    # 5. Group DRO
    L += ["## 5. Group DRO instead of ERM (seeds 0-1)", "",
          "| Task | Loss | Learned | Fixed | MLP | Fixed − learned | inject ratio learned / fixed |",
          "| :--- | :--- | :---: | :---: | :---: | ---: | :---: |"]
    for t in TASKS:
        gd = runs(dl("vlm-shortcut-r4-groupdro", "qwen35-4b_gdro", t))
        for lab, rs in (("ERM", H1[t]), ("Group DRO", gd)):
            s = [0, 1]
            lo = [wga(rs[("bottleneck", x)]) for x in s]
            fx = [wga(rs[("bottleneck_fixed", x)]) for x in s]
            ir = [inj(rs[(c, x)]) for c in ("bottleneck", "bottleneck_fixed") for x in s]
            irs = f"{np.mean(ir[:2]):.1f} / {np.mean(ir[2:]):.0f}" if None not in ir else "–"
            L.append(f"| {t} | {lab} | {fmt(lo)} | {fmt(fx)} | {cell(rs, 'mlp', s)[0]} | {np.mean(fx) - np.mean(lo):+.1f} | {irs} |")
    L += ["", "Reading: Group DRO, which uses group labels in training, raises the learned-gate model most and "
          "shrinks the gap, even though the learned gate still injects about 25× less visual signal than the fixed gate. "
          "So the narrow pathway carries enough information; with plain ERM the zero-initialised gate makes the "
          "model fall back on the shortcut. The fixed gate still matches or beats it. Two seeds: descriptive.", ""]

    # 6. injection ratio
    L += ["## 6. How much visual signal passes the gate (injection ratio ‖injected‖ / ‖text‖, test set)", "",
          "| Run set | Learned | Open | Fixed | Runs (learned / open / fixed) |", "| :--- | :---: | :---: | :---: | :---: |"]
    sets = [("Qwen, ERM (r4-inject + r4-wm-seeds)", [dl("vlm-shortcut-r4-inject", "qwen35-4b_inject", t) for t in TASKS]
             + [dl("vlm-shortcut-r4-wm-seeds", "qwen35-4b", "watermark_p0.95")]),
            ("Qwen, open-gate job", [dl("vlm-shortcut-r3-opengate", "qwen35-4b", t) for t in TASKS]),
            ("Qwen, Group DRO", [dl("vlm-shortcut-r4-groupdro", "qwen35-4b_gdro", t) for t in TASKS]),
            ("SigLIP-large, ERM", [dl("vlm-shortcut-r4-inject-large", "qwen35-4b_siglip-large_inject", "waterbirds")])]
    pairs = []
    for lab, roots in sets:
        v = {c: [] for c in ("bottleneck", "bottleneck_open", "bottleneck_fixed")}
        for r in roots:
            for (c, s), res in runs(r).items():
                if c in v and inj(res) is not None:
                    v[c].append(inj(res))
                    if c == "bottleneck":
                        pairs.append((inj(res), wga(res)))
        f = lambda x: f"{np.mean(x):.1f} (range {min(x):.1f}–{max(x):.1f})" if x else "–"
        L.append(f"| {lab} | {f(v['bottleneck'])} | {f(v['bottleneck_open'])} | {f(v['bottleneck_fixed'])} | "
                 f"{len(v['bottleneck'])} / {len(v['bottleneck_open'])} / {len(v['bottleneck_fixed'])} |")
    rho = stats.spearmanr([x for x, _ in pairs], [y for _, y in pairs])
    L += ["", f"Reading: the learned gate passes about 15–35× less visual signal than the fixed or open gate (raw ratios; the "
          f"text-embedding norm of Qwen3.5 is small, so values above 1 are expected). Across the {len(pairs)} learned-gate runs, injection ratio vs WGA: Spearman ρ = "
          f"{rho.statistic:.2f} (p = {rho.pvalue:.2g}). So the pathway is not closed: with tanh α ≈ 0.003 the injected signal is still 1–7× the text-embedding "
          "norm, because the output projection grows to compensate, and the gate value alone understates the injection. "
          "But it stays an order of magnitude below the fixed gate, and within the learned-gate runs its size does "
          "not predict WGA. The gate changes *how much* visual signal is injected, not whether any is.", ""]

    # 7. SigLIP-large and CelebA
    L += ["## 7. Stronger encoder (SigLIP-large) and a third task (CelebA)", "",
          "| Setting | Task | Seeds (paired) | Learned | Fixed | MLP | Q-Former | Fixed − learned | p one-sided |",
          "| :--- | :--- | :---: | :---: | :---: | :---: | :---: | ---: | ---: |"]
    for lab, root, tasks in (("SigLIP-large", a.siglip, TASKS), ("Qwen + SigLIP-base", os.path.dirname(a.celeba), ("celeba",))):
        for t in tasks:
            rs = runs(os.path.join(root, t))
            s, lo, fx = paired(rs, rs)
            pv = stats.ttest_rel(fx, lo, alternative="greater").pvalue if len(s) > 1 else float("nan")
            L.append(f"| {lab} | {t} | {len(s)} | {fmt(lo)} | {fmt(fx)} | {cell(rs, 'mlp', s)[0]} | {cell(rs, 'qformer', s)[0]} | "
                     f"{fx.mean() - lo.mean():+.1f} | {pv:.2g} |")
    L += ["", "Reading: with the stronger encoder the gate effect is smaller and not reliable (few seeds), "
          "consistent with the gate being a risk factor rather than a sufficient cause. CelebA (third task, 3 paired "
          "seeds): +13.3 in the same direction, not significant.", ""]

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
