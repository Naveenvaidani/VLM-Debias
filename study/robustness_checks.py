"""Reviewer robustness checks for the gate hypothesis (H1).

For learned vs fixed gate, per task:
  1. checkpoint selection: best val worst-group accuracy (uses group labels) vs best val average accuracy (label-free);
  2. test choice: paired t-test (seeds share data order and LoRA init) vs unpaired Welch t-test and Mann-Whitney U;
  3. accuracy trade-off: average and in-distribution (ID) accuracy next to worst-group accuracy.

Usage: python study/robustness_checks.py --runs_dir kaggle_out/h1_merged --out results_study/robustness_checks.md
"""
import argparse
import glob
import json
import os
import re

import numpy as np
from scipy import stats

ARMS = ("bottleneck", "bottleneck_fixed")


def load(runs_dir, task):
    out = {}
    for arm in ARMS:
        for f in glob.glob(os.path.join(runs_dir, "**", task, arm, "s*", "results.json"), recursive=True):
            seed = int(re.search(r"/s(\d+)/results\.json$", f).group(1))
            test = json.load(open(f))["test"]
            for rule in ("wga", "avg"):
                out.setdefault((arm, rule), {})[seed] = test[rule]["mean_over_templates"]
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--runs_dir", default="kaggle_out/h1_merged")
    p.add_argument("--tasks", default="waterbirds,watermark_p0.95")
    p.add_argument("--out", default="results_study/robustness_checks.md")
    args = p.parse_args()
    lines = ["# Robustness checks for H1 (fixed vs learned gate, Qwen3.5-4B)", "",
             "Generated by `study/robustness_checks.py`. Values are test means over seeds, in %. "
             "One-sided tests (fixed > learned) unless marked two-sided.", "",
             "| Task | Checkpoint rule | Seeds | WGA learned | WGA fixed | Gain | Paired t p | Welch t p | Mann-Whitney p "
             "| Avg acc learned | Avg acc fixed | Avg p (two-sided) | ID acc learned | ID acc fixed |",
             "| :--- | :--- | :---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for task in args.tasks.split(","):
        data = load(args.runs_dir, task)
        for rule, name in (("wga", "val WGA (group labels)"), ("avg", "val average (label-free)")):
            seeds = sorted(set(data[(ARMS[0], rule)]) & set(data[(ARMS[1], rule)]))
            get = lambda arm, key: np.array([data[(arm, rule)][s][key] for s in seeds]) * 100
            L, F = get(ARMS[0], "worst_group_acc"), get(ARMS[1], "worst_group_acc")
            LA, FA = get(ARMS[0], "avg_acc"), get(ARMS[1], "avg_acc")
            LI, FI = get(ARMS[0], "acc_id"), get(ARMS[1], "acc_id")
            paired = stats.ttest_rel(F, L, alternative="greater").pvalue
            welch = stats.ttest_ind(F, L, equal_var=False, alternative="greater").pvalue
            mw = stats.mannwhitneyu(F, L, alternative="greater").pvalue
            avg_p = stats.ttest_rel(FA, LA).pvalue
            lines.append(f"| {task} | {name} | {len(seeds)} | {L.mean():.1f} | {F.mean():.1f} | {F.mean() - L.mean():+.1f} "
                         f"| {paired:.2g} | {welch:.2g} | {mw:.2g} | {LA.mean():.1f} | {FA.mean():.1f} | {avg_p:.2g} "
                         f"| {LI.mean():.1f} | {FI.mean():.1f} |")
    # pilot vs confirmation: H1/H2 were written after the 3-seed pilot (seeds 0-2); seeds >= 3 are new data
    lines += ["", "## Pilot (seeds 0-2) vs confirmation sample (seeds 3 and later)", "",
              "H1 was formulated after a 3-seed pilot. Testing it only on the seeds run afterwards avoids using the "
              "same data to form and test the hypothesis.", "",
              "| Task | Sample | Seeds | WGA learned | WGA fixed | Gain | Paired t | p (one-sided) | Wilcoxon p | d_z |",
              "| :--- | :--- | :---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for task in args.tasks.split(","):
        data = load(args.runs_dir, task)
        both = sorted(set(data[(ARMS[0], "wga")]) & set(data[(ARMS[1], "wga")]))
        for name, seeds in (("pilot", [s for s in both if s < 3]), ("confirmation", [s for s in both if s >= 3])):
            L = np.array([data[(ARMS[0], "wga")][s]["worst_group_acc"] for s in seeds]) * 100
            F = np.array([data[(ARMS[1], "wga")][s]["worst_group_acc"] for s in seeds]) * 100
            d = F - L
            t = stats.ttest_rel(F, L, alternative="greater")
            w = stats.wilcoxon(F, L, alternative="greater").pvalue
            lines.append(f"| {task} | {name} | {len(seeds)} | {L.mean():.1f} | {F.mean():.1f} | {d.mean():+.1f} | "
                         f"{t.statistic:.2f} | {t.pvalue:.2g} | {w:.2g} | {d.mean() / d.std(ddof=1):.2f} |")
    lines += ["", "Reading: the gain survives label-free model selection and tests that do not pair seeds, and the "
              "fixed gate raises average accuracy as well, so the worst-group gain is not bought with accuracy elsewhere."]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
