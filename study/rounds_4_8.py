"""
Analysis of the round 4-8 Kaggle runs (pathway ablation, gate controls, shortcut-strength sweep, per-layer gates,
fp16, half-open gate, Group DRO, 8 epochs, SigLIP-large Watermark, CelebA, VQA-CP v2).
Baselines (default learned / fixed gate, Qwen3.5-4B, 4-bit) come from the committed results_study/h1/all_runs.csv.

    python study/rounds_4_8.py --dl kaggle_out --out results_study/rounds_4_8.md
"""
import argparse
import glob
import json
import os

import numpy as np
import pandas as pd
from scipy import stats

GATE = {"bottleneck": "learned gate", "bottleneck_fixed": "fixed gate", "bottleneck_open": "open init (α=3)",
        "bottleneck_half": "half-open init (tanh α=0.5)", "mlp": "MLP", "qformer": "Q-Former",
        "xattn_deep": "per-layer, learned gates", "xattn_deep_fixed": "per-layer, fixed gates"}


def runs(dl, job):
    rows = []
    for f in sorted(glob.glob(os.path.join(dl, job, "results", "*", "*", "*", "s*", "results.json"))):
        p = f.split(os.sep)
        tag, task, conn, seed = p[-5], p[-4], p[-3], int(p[-2][1:])
        d = json.load(open(f))
        w = d["test"]["wga"]
        m, a = w["mean_over_templates"], w.get("ablated_mean_over_templates") or {}
        h = d["history"][-1] if d["history"] else {}
        gm = h.get("gate_tanh")
        if gm is None and h.get("gates_tanh"):
            gm = float(np.mean(np.abs(h["gates_tanh"])))
        rows.append(dict(tag=tag, task=task, connector=conn, seed=seed, wga=100 * m["worst_group_acc"], avg=100 * m["avg_acc"],
                         wga_abl=100 * a["worst_group_acc"] if a else np.nan, avg_abl=100 * a["avg_acc"] if a else np.nan,
                         inject=m.get("inject_ratio", np.nan), gate=gm, epochs=len(d["history"]),
                         minutes=d["train_minutes"]))
    return pd.DataFrame(rows)


def base_runs(path="results_study/h1/all_runs.csv"):
    d = pd.read_csv(path)
    d = d[d.rule == "wga"].copy()
    d["wga"] = 100 * d.worst_group_acc
    d["avg"] = 100 * d.avg_acc
    return d.groupby(["task", "connector", "seed"], as_index=False)[["wga", "avg"]].mean()


def ms(v):
    v = np.asarray(v, float)
    v = v[~np.isnan(v)]
    if not len(v):
        return "–"
    return f"{v.mean():.1f} ± {v.std(ddof=1):.1f}" if len(v) > 1 else f"{v.mean():.1f}"


def paired(df, a, b, col="wga"):
    """b minus a over seeds both have; returns n, mean diff, p (two-sided paired t), d_z."""
    x = df[df.connector == a].groupby("seed")[col].mean()
    y = df[df.connector == b].groupby("seed")[col].mean()
    s = sorted(set(x.index) & set(y.index))
    if len(s) < 2:
        return len(s), (y[s] - x[s]).mean() if s else np.nan, np.nan, np.nan
    d = y[s].values - x[s].values
    t = stats.ttest_rel(y[s], x[s])
    return len(s), d.mean(), t.pvalue, d.mean() / d.std(ddof=1) if d.std(ddof=1) > 0 else np.nan


def pf(p):
    return "–" if p is None or np.isnan(p) else (f"{p:.1e}" if p < 0.001 else f"{p:.3f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dl", default="kaggle_out")
    ap.add_argument("--out", default="results_study/rounds_4_8.md")
    a = ap.parse_args()
    B = base_runs()
    L = ["# Round 4-8 runs: pathway ablation, gate controls, sweeps, VQA-CP", "",
         "Generated by `study/rounds_4_8.py`. Test worst-group accuracy (%), checkpoint chosen by validation WGA, mean ± SD "
         "over seeds. Baselines are the default 4-bit Qwen3.5-4B runs in `results_study/h1`. **Every test here is exploratory** "
         "(paired t-test, two-sided, small n); the four confirmatory H1 tests are in `extra_analyses.md` §1.", ""]

    def base_for(task, conn, seeds):
        d = B[(B.task == task) & (B.connector == conn) & (B.seed.isin(seeds))]
        return d

    # ---- 1 pathway ablation
    ab = runs(a.dl, "r5-controls")
    ab = ab[ab.tag == "qwen35-4b_ablate"]
    L += ["## 1. Pathway ablation (round 5)", "",
          "After training, the visual pathway is switched off at test time and the test set is scored again. With the image off "
          "every model gives one answer for every input, so worst-group accuracy is 0 by construction and only average accuracy "
          "is informative: it falls to the majority-class share (77.8% on Waterbirds, 50% on Watermark) when the model has no image.", "",
          "| Task | Connector | Seeds | WGA | Avg acc | Avg acc, image off | Drop | Injection ratio | Final tanh α |",
          "| :--- | :--- | :---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for (t, c), g in ab.groupby(["task", "connector"]):
        L.append(f"| {t} | {GATE[c]} | {len(g)} | {ms(g.wga)} | {ms(g.avg)} | {ms(g.avg_abl)} | {(g.avg - g.avg_abl).mean():.1f} | "
                 f"{g.inject.mean():.2f} | {g.gate.mean():.4f} |")
    L.append("")

    # ---- 2 gate protection controls
    L += ["## 2. Protecting the learned gate (round 5)", "",
          "Same learned gate, one change: the gate is left out of gradient clipping (`clipx`) or out of weight decay (`nowd`). "
          "Difference is control minus default learned gate on the same seeds.", "",
          "| Control | Task | Seeds | Control WGA | Default learned WGA (same seeds) | Difference | p | Final tanh α |",
          "| :--- | :--- | :---: | ---: | ---: | ---: | ---: | ---: |"]
    r5 = runs(a.dl, "r5-controls")
    for tag, name in (("qwen35-4b_clipx", "gate out of clipping"), ("qwen35-4b_nowd", "gate without weight decay")):
        for t in ("waterbirds", "watermark_p0.95"):
            g = r5[(r5.tag == tag) & (r5.task == t)]
            sd = sorted(g.seed.unique())
            bs = base_for(t, "bottleneck", sd)
            m = pd.concat([g.assign(connector="ctrl")[["task", "connector", "seed", "wga"]], bs.assign(connector="base")[["task", "connector", "seed", "wga"]]])
            n, dm, p, _ = paired(m, "base", "ctrl")
            L.append(f"| {name} | {t} | {len(sd)} | {ms(g.wga)} | {ms(bs.groupby('seed').wga.mean())} | {dm:+.1f} | {pf(p)} | {g.gate.mean():.4f} |")
    L.append("")

    # ---- 3 shortcut strength sweep
    ps = runs(a.dl, "r5-psweep")
    L += ["## 3. Shortcut strength (Watermark, round 5)", "",
          "Watermark correlation p in training. p = 0.95 is the main setting (see `hypotheses.md`).", "",
          "| p | MLP | Learned gate | Fixed gate |", "| :--- | :---: | :---: | :---: |"]
    for t in ("watermark_p0.9", "watermark_p0.99"):
        g = ps[ps.task == t]
        L.append(f"| {t.split('p')[-1]} | {ms(g[g.connector == 'mlp'].wga)} ({(g.connector == 'mlp').sum()}) | "
                 f"{ms(g[g.connector == 'bottleneck'].wga)} ({(g.connector == 'bottleneck').sum()}) | "
                 f"{ms(g[g.connector == 'bottleneck_fixed'].wga)} ({(g.connector == 'bottleneck_fixed').sum()}) |")
    for lab_, c_ in (("MLP", "mlp"), ("learned", "bottleneck"), ("fixed", "bottleneck_fixed")):
        pass
    mm = {c_: B[(B.task == "watermark_p0.95") & (B.connector == c_)].groupby("seed").wga.mean() for c_ in ("mlp", "bottleneck", "bottleneck_fixed")}
    L.append(f"| 0.95 (main setting, `h1`) | {ms(mm['mlp']) if len(mm['mlp']) else '–'} | {ms(mm['bottleneck'])} | {ms(mm['bottleneck_fixed'])} |")
    L.append("")

    # ---- 4 per layer + fp16 + half gate
    L += ["## 4. Per-layer gates, full precision, half-open gate (rounds 6-7)", "",
          "| Setting | Task | Learned | Fixed | Gain (fixed − learned) | Seeds | p | Final |tanh α|, learned |", "| :--- | :--- | :---: | :---: | ---: | :---: | ---: | ---: |"]
    for job, tag, lc, fc, name in (("r6-deep", "qwen35-4b_deep", "xattn_deep", "xattn_deep_fixed", "per-layer gates (4-bit)"),
                                   ("r6-fp16", "qwen35-4b_fp16", "bottleneck", "bottleneck_fixed", "single block, fp16 weights")):
        d = runs(a.dl, job)
        for t in ("waterbirds", "watermark_p0.95"):
            g = d[(d.task == t)]
            n, dm, p, _ = paired(g, lc, fc)
            gl = g[g.connector == lc]
            L.append(f"| {name} | {t} | {ms(g[g.connector == lc].wga)} | {ms(g[g.connector == fc].wga)} | {dm:+.1f} | {n} | {pf(p)} | {gl.gate.abs().mean() if gl.gate.notna().any() else float('nan'):.4f} |")
    for t in ("waterbirds", "watermark_p0.95"):
        d = B[(B.task == t) & (B.seed < 5)]
        n, dm, p, _ = paired(d, "bottleneck", "bottleneck_fixed")
        L.append(f"| single block, 4-bit (default, seeds 0-4) | {t} | {ms(d[d.connector == 'bottleneck'].wga)} | {ms(d[d.connector == 'bottleneck_fixed'].wga)} | {dm:+.1f} | {n} | {pf(p)} | – |")
    L.append("")
    hg = runs(a.dl, "r7-halfgate")
    L += ["Half-open gate: the learnable gate starts at tanh α = 0.5 (gradient scale 0.75), seeds 0-4.", "",
          "| Task | Half-open init | Learned (zero init) | Fixed | Final |tanh α|, half-open | Half-open − learned (p) | Half-open − fixed (p) |",
          "| :--- | :---: | :---: | :---: | :---: | :---: | :---: |"]
    for t in ("waterbirds", "watermark_p0.95"):
        g = hg[hg.task == t]
        bs = B[(B.task == t) & (B.seed < 5)]
        m = pd.concat([g[["task", "connector", "seed", "wga"]], bs[["task", "connector", "seed", "wga"]]])
        _, d1, p1, _ = paired(m, "bottleneck", "bottleneck_half")
        _, d2, p2, _ = paired(m, "bottleneck_fixed", "bottleneck_half")
        L.append(f"| {t} | {ms(g.wga)} | {ms(bs[bs.connector == 'bottleneck'].groupby('seed').wga.mean())} | "
                 f"{ms(bs[bs.connector == 'bottleneck_fixed'].groupby('seed').wga.mean())} | {g.gate.abs().mean():.3f} | {d1:+.1f} ({pf(p1)}) | {d2:+.1f} ({pf(p2)}) |")
    L.append("")

    # ---- 5 group DRO + lr
    gd = pd.concat([runs(a.dl, "r4-groupdro"), runs(a.dl, "r7-gdro-lr")])
    gd = gd[gd.tag == "qwen35-4b_gdro"]
    L += ["## 5. Group DRO (rounds 4 and 7)", "",
          "Group DRO over the four groups (uses group labels), seeds 0-1 (round 4) and 2-3 (round 7).", "",
          "| Task | Connector | Seeds | WGA | Avg acc |", "| :--- | :--- | :---: | ---: | ---: |"]
    for (t, c), g in gd.groupby(["task", "connector"]):
        L.append(f"| {t} | {GATE[c]} | {len(g)} | {ms(g.wga)} | {ms(g.avg)} |")
    for t in ("waterbirds", "watermark_p0.95"):
        g = gd[gd.task == t]
        n, dm, p, dz = paired(g, "bottleneck", "bottleneck_fixed")
        L.append(f"| {t} | fixed − learned under DRO | {n} | {dm:+.1f} (p = {pf(p)}) | |")
    L += ["", "Round 7 also queued connector learning rates 5e-5 and 1e-3 for Waterbirds (seeds 2-4). Only their alignment stage finished; "
          "the task runs were skipped (`not enough session time left`), so there is no new learning-rate result.", ""]

    # ---- 6 long training
    lg = runs(a.dl, "r4-long8")
    old = pd.read_csv("results_study/long8/all_runs.csv")
    old = old[old.rule == "wga"]
    old = pd.DataFrame(dict(task=old.task, connector=old.connector, seed=old.seed, wga=100 * old.worst_group_acc))
    lg2 = pd.concat([lg[["task", "connector", "seed", "wga"]], old])
    L += ["## 6. Eight epochs instead of four (Waterbirds)", "",
          "Seed 0 from `results_study/long8`, seeds 1-4 from round 4.", "",
          "| Connector | Seeds | WGA (8 epochs) | per seed |", "| :--- | :---: | ---: | :--- |"]
    for c in ("mlp", "bottleneck", "bottleneck_fixed"):
        g = lg2[lg2.connector == c].sort_values("seed")
        L.append(f"| {GATE[c]} | {len(g)} | {ms(g.wga)} | {', '.join(f'{v:.1f}' for v in g.wga)} |")
    n, dm, p, _ = paired(lg2, "bottleneck", "bottleneck_fixed")
    L += ["", f"Fixed − learned at 8 epochs: {dm:+.1f} points over {n} seeds, p = {pf(p)} (exploratory).", ""]

    # ---- 7 encoder + celeba
    sw = runs(a.dl, "r7-siglip-wm")
    old = pd.read_csv("results_study/siglip_large/all_runs.csv")
    old = old[(old.rule == "wga") & (old.task == "watermark_p0.95")]
    old = pd.DataFrame(dict(task=old.task, connector=old.connector, seed=old.seed, wga=100 * old.worst_group_acc))
    wm = pd.concat([sw[["task", "connector", "seed", "wga"]], old])
    n, dm, p, dz = paired(wm, "bottleneck", "bottleneck_fixed")
    L += ["## 7. SigLIP-large features, Watermark, seeds 0-4", "",
          f"Learned gate {ms(wm[wm.connector == 'bottleneck'].wga)}, fixed gate {ms(wm[wm.connector == 'bottleneck_fixed'].wga)}; "
          f"gain {dm:+.1f} over {n} paired seeds, p = {pf(p)}, d_z = {dz:.2f}. "
          "(Earlier, with 2 seeds, the difference was 0.6 points.)", ""]
    cb = runs(a.dl, "r7-celeba")
    oldc = pd.read_csv("results_study/celeba/all_runs.csv")
    oldc = oldc[oldc.rule == "wga"]
    oldc = pd.DataFrame(dict(task=oldc.task, connector=oldc.connector, seed=oldc.seed, wga=100 * oldc.worst_group_acc))
    cbm = pd.concat([cb[["task", "connector", "seed", "wga"]], oldc])
    n, dm, p, _ = paired(cbm, "bottleneck", "bottleneck_fixed")
    L += ["## 8. CelebA with the round 7 seeds", "",
          "| Connector | Seeds | WGA |", "| :--- | :---: | ---: |"]
    for c in ("mlp", "bottleneck", "bottleneck_fixed"):
        g = cbm[cbm.connector == c]
        L.append(f"| {GATE[c]} | {g.seed.nunique()} | {ms(g.groupby('seed').wga.mean())} |")
    L += ["", f"Fixed − learned: {dm:+.1f} over {n} paired seeds, p = {pf(p)}.", ""]

    # ---- 9 open gate / inject reruns
    ij = runs(a.dl, "r4-inject")
    L += ["## 9. Open-gate rerun with logging (round 4, seeds 0-1)", "",
          "| Task | Connector | WGA | Final tanh α | Injection ratio |", "| :--- | :--- | ---: | ---: | ---: |"]
    for (t, c), g in ij.groupby(["task", "connector"]):
        L.append(f"| {t} | {GATE[c]} | {ms(g.wga)} | {g.gate.abs().mean():.4f} | {g.inject.mean():.2f} |")
    L.append("")

    # ---- 10 VQA-CP
    rows = []
    for f in sorted(glob.glob(os.path.join(a.dl, "r8-vqacp", "results", "*", "*", "s*", "results.json"))):
        p_ = f.split(os.sep)
        d = json.load(open(f))
        t = d["test"]
        rows.append(dict(connector=p_[-3], seed=int(p_[-2][1:]), val=d["val_vqa_acc"],
                         id=100 * t["test_id"]["vqa_acc"], ood=100 * t["test_ood"]["vqa_acc"],
                         id_abl=100 * t["test_id_ablated"]["vqa_acc"], ood_abl=100 * t["test_ood_ablated"]["vqa_acc"],
                         prior_id=100 * t["test_id"]["prior_answer_rate"], prior_ood=100 * t["test_ood"]["prior_answer_rate"],
                         inject=t["test_id"].get("inject_ratio", np.nan),
                         yn=100 * t["test_ood"]["acc[yes/no]"], num=100 * t["test_ood"]["acc[number]"], oth=100 * t["test_ood"]["acc[other]"]))
    V = pd.DataFrame(rows)
    V.to_csv(os.path.join(os.path.dirname(a.out), "vqacp_runs.csv"), index=False)
    L += ["## 10. VQA-CP v2: open-ended answers on natural images (round 8, 3 seeds)", "",
          "VQA accuracy (%) from free-form generation, scored against 10 human answers. Test-ID has the same answer priors as "
          "training; test-OOD is the VQA-CP test split, where the prior answer is never the majority answer. "
          "'Image off' repeats the test with the visual pathway removed. 8,000 training questions, 3 epochs, subset of VQA-CP: "
          "**not comparable to published VQA-CP numbers**.", "",
          "| Connector | Seeds | Test-ID | Test-ID, image off | Test-OOD | Test-OOD, image off | ID − OOD | Prior answer, ID / OOD (%) | Injection ratio |",
          "| :--- | :---: | ---: | ---: | ---: | ---: | ---: | :---: | ---: |"]
    for c in ("bottleneck", "bottleneck_fixed"):
        g = V[V.connector == c]
        L.append(f"| {GATE[c]} | {len(g)} | {ms(g.id)} | {ms(g.id_abl)} | {ms(g.ood)} | {ms(g.ood_abl)} | {(g.id - g.ood).mean():.1f} | "
                 f"{g.prior_id.mean():.1f} / {g.prior_ood.mean():.1f} | {g.inject.mean():.2f} |")
    cc = V.rename(columns={"id": "wga"})
    n, dm, p, _ = paired(cc.assign(wga=cc.wga), "bottleneck", "bottleneck_fixed")
    cc2 = V.rename(columns={"ood": "wga"})
    n, dm2, p2, _ = paired(cc2, "bottleneck", "bottleneck_fixed")
    L += ["", f"Fixed − learned: test-ID {dm:+.1f} (p = {pf(p)}), test-OOD {dm2:+.1f} (p = {pf(p2)}), paired over {n} seeds.", ""]
    for c in ("bottleneck", "bottleneck_fixed"):
        g = V[V.connector == c]
        L.append(f"- {GATE[c]}: switching the image off changes test-ID by {(g.id_abl - g.id).mean():+.1f} and test-OOD by "
                 f"{(g.ood_abl - g.ood).mean():+.1f} points.")
    L.append("")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
